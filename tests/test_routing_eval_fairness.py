"""Routing eval v2, step 2: G6 fair views (eval-spec-v2 §0 G6, §10.2).

Every arm's view is generated by code from the same world; nothing is hand-written for
one arm. Two parts:
  1. invariants on every world at N=10 (both similarity levels): same agents, names,
     briefs, history and incoming message in every arm;
  2. byte-for-byte snapshots of each arm's full view for a few fixed worlds
     (regenerate with ROUTING_EVAL_UPDATE_SNAPSHOTS=1 and review the diff).
"""

from __future__ import annotations

import html
import inspect
import json
import os
import re
import sys
from pathlib import Path

import pytest

import harness

sys.path.append(str(Path(__file__).resolve().parent.parent))  # repo root (after the sandbox copy)

from routing_eval import catalog, views  # noqa: E402
from routing_eval.generator import build_world, generate  # noqa: E402

from server.agents.interaction_agent import agent as ia_agent  # noqa: E402
from server.services.conversation.summarization.working_memory_log import WorkingMemoryLog  # noqa: E402

SNAP_DIR = Path(__file__).parent / "snapshots" / "routing_eval"
SNAPSHOT_WORLDS = [
    ("seed_bob_server_crash", 10, "high"), ("seed_bob_server_crash", 50, "low"),
    ("pf_refund", 10, "high"), ("drift_oil_change", 10, "high"),
    ("seed_northwind_remittance", 3, "high"), ("os_nb_fifth", 3, "high"),
]
PAIRS, _ = generate(plan=((10, "high"),))
_PREFIX_RE = re.compile(r"^\[SUCCESS\] (?:ea_\d+ \((?P<n1>.*?)\)|(?P<n2>.*?)): ", re.S)


def _probe(pid):
    return next(p for p in catalog.PROBES if p.probe_id == pid)


def _registry_message(world, inst, tmp_path, name):
    """The registry IA's user message (real prepare_message_with_history) and its agent rows."""
    sb = harness.open_sandbox(tmp_path / name)
    try:
        view = views.load_registry(world, sb.registry, sb.triggers._store, sb.data_dir / "conversation")
        real_transcript = WorkingMemoryLog(sb.data_dir / "conversation/poke_working_memory.log").render_transcript()
        assert real_transcript == views.transcript(world, "registry")
        with views.world_clock(world, sb.registry):
            msgs = ia_agent.prepare_message_with_history(inst.message, real_transcript,
                                                         message_type=views.message_type(inst.source))
        rows = []
        for a in world.agents:
            rec = sb.registry.get(view.id_of[a.ref])
            rows.append((rec.label, rec.brief))
        return view, msgs[0]["content"], rows
    finally:
        sb.close()


def _strip_prefix(payload):
    m = _PREFIX_RE.match(payload)
    assert m, payload
    return (m.group("n1") or m.group("n2")), payload[m.end():]


def test_view_builders_take_only_the_world():
    """No arm-specific text inputs: each builder's only content input is the World."""
    for fn in (views.load_baseline, views.rag_roster, views.load_registry, views.conversation_entries,
               views.transcript, views.baseline_ia_message, views.summary_text, views.rag_query, views.last_turns):
        params = list(inspect.signature(fn).parameters)
        assert params[0] == "world", fn.__name__
        assert not {"brief", "label", "name", "notes", "text"} & set(params), fn.__name__


def test_every_arm_sees_the_same_world(tmp_path):
    for i, (world, inst) in enumerate(PAIRS):
        names = [a.name for a in world.agents]
        briefs = [a.brief for a in world.agents]
        # baseline
        base = views.load_baseline(world, tmp_path / f"b{i}")
        assert set(base.roster) == set(names)
        base_msg = views.baseline_ia_message(world, inst.message, inst.source)
        # registry
        _reg_view, reg_msg, rows = _registry_message(world, inst, tmp_path, f"r{i}")
        assert rows == list(zip(names, briefs)), world.world_id
        # rag (both variants)
        for variant in views.RAG_VARIANTS:
            docs = views.rag_roster(world, variant)
            assert [d["name"] for d in docs] == names
            assert all(d["topic"].startswith(b) for d, b in zip(docs, briefs))
            assert views.rag_query(world, inst.message, variant).endswith(inst.message)
        # same incoming message, same turn type
        tag = "new_agent_message" if views.message_type(inst.source) == "agent" else "new_user_message"
        for msg in (base_msg, reg_msg):
            assert msg.endswith(f"<{tag}>\n{inst.message.strip()}\n</{tag}>")
        # same history: identical entries except the agent_message prefix (code-version format)
        b_entries = views.conversation_entries(world, "baseline")
        r_entries = views.conversation_entries(world, "registry")
        assert len(b_entries) == len(r_entries)
        for (bt, bts, bp), (rt, rts, rp) in zip(b_entries, r_entries):
            assert (bt, bts) == (rt, rts)
            if bt == "agent_message":
                assert _strip_prefix(bp) == _strip_prefix(rp)
            else:
                assert bp == rp
        # every agent name either arm shows comes from the world
        shown = {html.unescape(n) for n in re.findall(r'<agent name="(.*?)" />', base_msg)}  # 5b5f635 escapes names
        assert shown <= set(names) and shown == set(base.roster)


def _render(world, inst, tmp_path) -> str:
    base = views.load_baseline(world, tmp_path / "base")
    roster = json.loads((tmp_path / "base/execution_agents/roster.json").read_text())
    real_base_transcript = WorkingMemoryLog(tmp_path / "base/conversation/poke_working_memory.log").render_transcript()
    assert real_base_transcript == views.transcript(world, "baseline")
    _view, reg_msg, _reg = _registry_message(world, inst, tmp_path, "reg")
    out = [
        f"# world {world.world_id} (seed {world.seed}); probe message source={inst.source}",
        "=== baseline: roster.json ===", json.dumps(roster, indent=2),
        "=== baseline: IA user message ===", views.baseline_ia_message(world, inst.message, inst.source),
        "=== registry: IA user message ===", reg_msg,
    ]
    for variant in views.RAG_VARIANTS:
        out += [f"=== rag {variant}: roster dicts ===", json.dumps(views.rag_roster(world, variant), indent=2),
                f"=== rag {variant}: query ===", views.rag_query(world, inst.message, variant)]
    assert base.roster == tuple(roster)
    return "\n".join(out) + "\n"


@pytest.mark.parametrize("pid,n,sim", SNAPSHOT_WORLDS)
def test_view_snapshots(pid, n, sim, tmp_path):
    world = build_world(_probe(pid), n, sim)
    from routing_eval.generator import instance
    rendered = _render(world, instance(_probe(pid), world), tmp_path)
    path = SNAP_DIR / f"{world.world_id}.txt"
    if os.environ.get("ROUTING_EVAL_UPDATE_SNAPSHOTS") == "1":
        SNAP_DIR.mkdir(parents=True, exist_ok=True)
        path.write_text(rendered, encoding="utf-8")
    if not path.exists():
        pytest.fail(f"missing snapshot {path}; run with ROUTING_EVAL_UPDATE_SNAPSHOTS=1 and review it")
    assert rendered == path.read_text(encoding="utf-8"), f"view drifted from {path.name}"
